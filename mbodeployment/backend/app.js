// CUSTOMER ORDER STATUS — SIX-DIGIT CODE ONLY
//
// GET /api/orders/status?code=123456
//
// The frontend sends only six digits. The backend generates
// today's South African date prefix and searches for the full
// reference. It also supports unique historical suffixes.
// ==========================================================

app.get(
    '/api/orders/status',
    customerOrderStatusLimiter,
    async (req, res) => {
        setNoCache(res);

        try {
            const orderCode = String(
                req.query.code || ''
            ).trim();

            if (!ORDER_CODE_PATTERN.test(orderCode)) {
                return res.status(400).json({
                    error:
                        'Enter the six-digit order code shown after checkout.',
                });
            }

            const todayOrderNumber =
                `MBO-${getSouthAfricanDateStamp()}-${orderCode}`;

            const orderSelect = `
                id,
                order_number,
                order_type,
                payment_method,
                status,
                subtotal,
                created_at,
                updated_at,
                order_items (
                    quantity,
                    price,
                    menu_items (
                        id,
                        name
                    )
                )
            `;

            // --------------------------------------------------
            // 1. TRY TODAY'S SOUTH AFRICAN REFERENCE
            // --------------------------------------------------

            const {
                data: todayOrder,
                error: todayLookupError,
            } = await supabase
                .from('orders')
                .select(orderSelect)
                .eq('order_number', todayOrderNumber)
                .maybeSingle();

            if (todayLookupError) {
                console.error(
                    'TODAY ORDER CODE LOOKUP ERROR:',
                    todayLookupError.code ||
                        todayLookupError.message
                );

                return res.status(500).json({
                    error: 'Failed to fetch order status',
                });
            }

            let order = todayOrder || null;

            // --------------------------------------------------
            // 2. SUPPORT HISTORICAL ORDER REFERENCES
            // --------------------------------------------------
            //
            // A customer might return on a different day.
            // Search older references by their six-digit suffix.
            //
            // Legacy daily counters may have produced duplicate
            // suffixes. In that case, refuse to guess.
            // --------------------------------------------------

            if (!order) {
                const {
                    data: matchingOrders,
                    error: suffixLookupError,
                } = await supabase
                    .from('orders')
                    .select(orderSelect)
                    .like(
                        'order_number',
                        `MBO-______-${orderCode}`
                    )
                    .order('created_at', {
                        ascending: false,
                    })
                    .limit(2);

                if (suffixLookupError) {
                    console.error(
                        'HISTORICAL ORDER CODE LOOKUP ERROR:',
                        suffixLookupError.code ||
                            suffixLookupError.message
                    );

                    return res.status(500).json({
                        error: 'Failed to fetch order status',
                    });
                }

                if ((matchingOrders || []).length > 1) {
                    return res.status(409).json({
                        code: 'ORDER_CODE_AMBIGUOUS',
                        error:
                            'This code matches more than one older order. Please contact Mbo’s Tshisanyama and provide the full order reference shown on your receipt.',
                    });
                }

                order = matchingOrders?.[0] || null;
            }

            // --------------------------------------------------
            // 3. NO MATCH
            // --------------------------------------------------

            if (!order) {
                return res.status(200).json({
                    order: null,
                });
            }

            // --------------------------------------------------
            // 4. RETURN PUBLIC TRACKING INFORMATION
            // --------------------------------------------------
            //
            // The six-digit code is the only customer credential.
            // Do not expose phone numbers, customer names, private
            // notes or delivery coordinates through this endpoint.
            // --------------------------------------------------

            return res.status(200).json({
                order: {
                    order_id: order.id,
                    order_number: order.order_number,
                    order_type: order.order_type,
                    payment_method: order.payment_method,
                    status: order.status,
                    subtotal: order.subtotal,
                    created_at: order.created_at,
                    updated_at: order.updated_at,
                    items: (order.order_items || []).map(
                        formatOrderItem
                    ),
                },
            });
        } catch (error) {
            console.error(
                'UNEXPECTED CUSTOMER STATUS ERROR:',
                error.message
            );

            return res.status(500).json({
                error: 'Internal server error',
            });
        }
    }
);

