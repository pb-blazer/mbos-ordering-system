/**
 * Creates a stable SHA-256 fingerprint of the validated order.
 *
 * The same checkout must produce the same request hash when retried.
 * This supports safe recovery from network failures without creating
 * duplicate production orders.
 */
function createOrderRequestHash({
    name,
    phone,
    order_type,
    payment_method,
    cleanNotes,
    cleanItems,
    latitude,
    longitude,
}) {
    const canonicalPayload = {
        customer: {
            name,
            phone,
        },

        order_type,
        payment_method,
        notes: cleanNotes,

        items: [...cleanItems]
            .sort(
                (a, b) => a.menu_item_id - b.menu_item_id
            )
            .map((item) => ({
                menu_item_id: item.menu_item_id,
                quantity: item.quantity,
                expected_price: item.expected_price,
            })),

        latitude:
            order_type === 'delivery' ? latitude : null,

        longitude:
            order_type === 'delivery' ? longitude : null,
    };

    return createHash('sha256')
        .update(JSON.stringify(canonicalPayload))
        .digest('hex');
}

/**
 * Checks whether a request key already exists.
 *
 * Existing requests are checked before menu availability so an order
 * that was already created can be recovered even if the menu changes.
 */
async function findExistingOrderRequest(idempotencyKey) {
    const { data, error } = await supabase
        .from('order_idempotency_keys')
        .select('request_hash, order_id')
        .eq('idempotency_key', idempotencyKey)
        .maybeSingle();

    if (error) {
        console.error(
            'IDEMPOTENCY LOOKUP ERROR:',
            error.code || error.message
        );

        const lookupError = new Error(
            'Could not safely check the previous order request.'
        );

        lookupError.code = 'IDEMPOTENCY_CHECK_UNAVAILABLE';

        throw lookupError;
    }

    return data || null;
}

