function formatOrderItem(item) {
    const price = Number(item.price);
    const quantity = Number(item.quantity);

    return {
        menu_item_id: item.menu_items?.id ?? null,
        name: item.menu_items?.name ?? 'Unavailable item',
        quantity,
        price,
        line_total: Number((price * quantity).toFixed(2)),
    };
}

function formatCustomer(customer, includeId = false) {
    if (!customer) {
        return null;
    }

    const formatted = {
        name: customer.name,
        phone: customer.phone,
    };

    if (includeId) {
        formatted.id = customer.id;
    }

    return formatted;
}

function formatAdminOrderSummary(order) {
    return {
        order_id: order.id,
        order_number: order.order_number,

        customer: order.customers
            ? {
                id: order.customers.id,
                name: order.customers.name,
                phone: order.customers.phone,
            }
            : null,

        order_type: order.order_type,
        payment_method: order.payment_method,
        status: order.status,
        subtotal: order.subtotal,
        notes: order.notes,
        created_at: order.created_at,
        updated_at: order.updated_at,
    };
}

