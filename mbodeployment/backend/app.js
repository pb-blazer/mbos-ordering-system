app.patch(
    '/api/admin/menu/:id',
    requireAdmin,
    async (req, res) => {
        try {
            const itemId = Number(req.params.id);

            if (!isPositiveInteger(itemId)) {
                return res.status(400).json({
                    error: 'Invalid menu item ID',
                });
            }

            const body = req.body || {};
            const updates = {};

            // --------------------------------------------------
            // NAME
            // --------------------------------------------------

            if (body.name !== undefined) {
                if (typeof body.name !== 'string') {
                    return res.status(400).json({
                        error: 'Menu item name must be text',
                    });
                }

                const value = body.name.trim();

                if (
                    value.length < 1 ||
                    value.length > 100
                ) {
                    return res.status(400).json({
                        error:
                            'Menu item name must be between 1 and 100 characters',
                    });
                }

                updates.name = value;
            }

            // --------------------------------------------------
            // CATEGORY
            // --------------------------------------------------

            if (body.category !== undefined) {
                if (typeof body.category !== 'string') {
                    return res.status(400).json({
                        error: 'Menu item category must be text',
                    });
                }

                const value = body.category.trim();

                if (
                    value.length < 1 ||
                    value.length > 100
                ) {
                    return res.status(400).json({
                        error:
                            'Menu item category must be between 1 and 100 characters',
                    });
                }

                updates.category = value;
            }

            // --------------------------------------------------
            // PRICE
            // --------------------------------------------------

            if (body.price !== undefined) {
                if (
                    body.price === null ||
                    body.price === '' ||
                    typeof body.price === 'boolean'
                ) {
                    return res.status(400).json({
                        error: 'Menu item price must be a valid number',
                    });
                }

                const price = Number(body.price);

                if (
                    !Number.isFinite(price) ||
                    price < 0 ||
                    price > 100000
                ) {
                    return res.status(400).json({
                        error:
                            'Menu item price must be between 0 and 100000',
                    });
                }

                updates.price = Number(price.toFixed(2));
            }

            // --------------------------------------------------
            // AVAILABILITY
            // --------------------------------------------------

            if (body.available !== undefined) {
                if (typeof body.available !== 'boolean') {
                    return res.status(400).json({
                        error: 'Availability must be true or false',
                    });
                }

                updates.available = body.available;
            }

            // --------------------------------------------------
            // DESCRIPTION
            // --------------------------------------------------

            if (body.description !== undefined) {
                if (
                    body.description !== null &&
                    typeof body.description !== 'string'
                ) {
                    return res.status(400).json({
                        error: 'Description must be text or null',
                    });
                }

                if (body.description === null) {
                    updates.description = null;
                } else {
                    const value = body.description.trim();

                    if (value.length > 1000) {
                        return res.status(400).json({
                            error:
                                'Description must be 1000 characters or less',
                        });
                    }

                    updates.description = value;
                }
            }

            // --------------------------------------------------
            // MENU LISTING / ARCHIVE STATE
            // --------------------------------------------------

            if (body.is_listed !== undefined) {
                if (typeof body.is_listed !== 'boolean') {
                    return res.status(400).json({
                        error: 'Menu listing state must be true or false',
                    });
                }

                updates.is_listed = body.is_listed;

                // Archiving always makes the item unavailable as well.
                // Restoring does not automatically mark it as available.
                if (body.is_listed === false) {
                    updates.available = false;
                }
            }

            // An archived item must be restored before staff can mark it
            // available again. This also protects against requests that
            // attempt to set available=true on an archived product.
            if (body.available === true && body.is_listed !== true) {
                const { data: currentItem, error: currentItemError } =
                    await supabase
                        .from('menu_items')
                        .select('id, is_listed')
                        .eq('id', itemId)
                        .maybeSingle();

                if (currentItemError) {
                    console.error(
                        'ADMIN MENU LISTING CHECK ERROR:',
                        currentItemError.code || currentItemError.message
                    );

                    return res.status(500).json({
                        error: 'Could not verify menu item listing state',
                    });
                }

                if (!currentItem) {
                    return res.status(404).json({
                        error: 'Menu item not found',
                    });
                }

                if (currentItem.is_listed !== true) {
                    return res.status(409).json({
                        error: 'Restore this menu item before marking it available',
                    });
                }
            }

            if (Object.keys(updates).length === 0) {
                return res.status(400).json({
                    error: 'No valid menu changes were provided',
                });
            }

            const {
                data: updatedItem,
                error,
            } = await supabase
                .from('menu_items')
                .update(updates)
                .eq('id', itemId)
                .select(
                    'id, name, category, price, available, description, is_listed'
                )
                .maybeSingle();

            if (error) {
                console.error(
                    'ADMIN MENU UPDATE ERROR:',
                    error.code || error.message
                );

                return res.status(500).json({
                    error: 'Failed to update menu item',
                });
            }

            if (!updatedItem) {
                return res.status(404).json({
                    error: 'Menu item not found',
                });
            }

            return res.status(200).json({
                message: 'Menu item updated successfully',
                item: updatedItem,
            });
        } catch (error) {
            console.error(
                'UNEXPECTED ADMIN MENU UPDATE ERROR:',
                error.message
            );

            return res.status(500).json({
                error: 'Internal server error',
            });
        }
    }
);

// ==========================================================
// 404 HANDLER
// ==========================================================

app.use((req, res) => {
    return res.status(404).json({
        error: 'Route not found',
    });
});

// ==========================================================
// GLOBAL ERROR HANDLER
// ==========================================================

app.use((error, req, res, next) => {
    if (res.headersSent) {
        return next(error);
    }

    if (
        error instanceof SyntaxError &&
        error.status === 400 &&
        'body' in error
    ) {
        return res.status(400).json({
            error: 'Invalid JSON request body',
        });
    }

    if (error.status === 413) {
        return res.status(413).json({
            error: 'Request body is too large',
        });
    }

    console.error(
        'GLOBAL ERROR:',
        error.message
    );

    return res.status(500).json({
        error: 'Internal server error',
    });
});

