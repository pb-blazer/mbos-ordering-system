// ==========================================================

function formatRpcError(error) {
    const message = String(error?.message || '');
    const lowerMessage = message.toLowerCase();

    // ------------------------------------------------------
    // IDEMPOTENCY ERRORS
    // ------------------------------------------------------

    if (message.includes('IDEMPOTENCY_KEY_REUSED:')) {
        return {
            status: 409,
            body: {
                code: 'IDEMPOTENCY_KEY_REUSED',
                error:
                    'This request key belongs to different order details. The previous order may already have been received. Check the order status or contact Mbo’s Tshisanyama before submitting another order.',
            },
        };
    }

    if (message.includes('IDEMPOTENCY_KEY_REQUIRED:')) {
        return {
            status: 400,
            body: {
                code: 'IDEMPOTENCY_KEY_REQUIRED',
                error: 'A valid order request key is required.',
            },
        };
    }

    if (message.includes('INVALID_REQUEST_HASH:')) {
        return {
            status: 400,
            body: {
                code: 'INVALID_REQUEST_HASH',
                error: 'The order request could not be validated.',
            },
        };
    }

    if (
        message.includes('IDEMPOTENCY_IN_PROGRESS:') ||
        message.includes('IDEMPOTENCY_RETRY:')
    ) {
        return {
            status: 503,
            body: {
                code: 'IDEMPOTENCY_IN_PROGRESS',
                error:
                    'The previous order request has not been confirmed yet. Keep your order details unchanged and retry safely.',
            },
        };
    }

    if (message.includes('IDEMPOTENCY_ORDER_MISSING:')) {
        return {
            status: 500,
            body: {
                error:
                    'The previous order could not be retrieved. Contact Mbo’s Tshisanyama before submitting another order.',
            },
        };
    }

    // ------------------------------------------------------
    // MENU PRICE CHANGES
    // ------------------------------------------------------

    if (message.includes('PRICE_CHANGED:')) {
        const detail = message
            .split('PRICE_CHANGED:')
            .pop()
            .trim();

        return {
            status: 409,
            body: {
                code: 'PRICE_CHANGED',
                error:
                    'A menu price changed while you were ordering. Return to menu and clear cart before placing your order again.',
                detail,
            },
        };
    }

    // ------------------------------------------------------
    // UNAVAILABLE ITEMS
    // ------------------------------------------------------

    if (
        lowerMessage.includes('sold out') ||
        lowerMessage.includes('not available') ||
        lowerMessage.includes('unavailable') ||
        lowerMessage.includes('does not exist') ||
        lowerMessage.includes('not found')
    ) {
        return {
            status: 409,
            body: {
                code: 'ITEM_UNAVAILABLE',
                error:
                    'One or more items are no longer available. Refresh the menu and review your order.',
            },
        };
    }

    // ------------------------------------------------------
    // VALIDATION ERRORS
    // ------------------------------------------------------

    if (
        lowerMessage.includes('required') ||
        lowerMessage.includes('invalid') ||
        lowerMessage.includes('must be') ||
        lowerMessage.includes('duplicate') ||
        lowerMessage.includes('quantity') ||
        lowerMessage.includes('collection orders') ||
        lowerMessage.includes('delivery orders') ||
        lowerMessage.includes('between 1 and 100') ||
        lowerMessage.includes('order item') ||
        lowerMessage.includes('latitude') ||
        lowerMessage.includes('longitude') ||
        lowerMessage.includes('expected price')
    ) {
        return {
            status: 400,
            body: {
                error:
                    'The order details are invalid. Check your information and try again.',
            },
        };
    }

    return {
        status: 500,
        body: {
            error:
                'We could not create your order. Please try again.',
        },
    };
}

