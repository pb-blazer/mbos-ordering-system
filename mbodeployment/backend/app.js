// ==========================================================
// SALES & BUSINESS ANALYTICS
// ADMIN ONLY
// GET /api/admin/analytics?from=YYYY-MM-DD&to=YYYY-MM-DD
//
// Revenue is calculated from COMPLETED orders only, using the
// stored orders.subtotal. Pending, cancelled and in-progress
// orders contribute to operational counts, not revenue.
// All date boundaries and daily buckets use South African time.
// ==========================================================

app.get(
    '/api/admin/analytics',
    requireAdmin,
    async (req, res) => {
        setNoCache(res);

        try {
            const { from, to } = req.query;

            const isValidDateOnly = (value) => {
                if (
                    typeof value !== 'string' ||
                    !/^\d{4}-\d{2}-\d{2}$/.test(value)
                ) {
                    return false;
                }

                const parsed = new Date(`${value}T00:00:00.000Z`);

                return (
                    !Number.isNaN(parsed.getTime()) &&
                    parsed.toISOString().slice(0, 10) === value
                );
            };

            const addDateOnlyDays = (value, days) => {
                const date = new Date(`${value}T12:00:00.000Z`);
                date.setUTCDate(date.getUTCDate() + days);
                return date.toISOString().slice(0, 10);
            };

            const southAfricanDateFormatter = new Intl.DateTimeFormat('en-GB', {
                timeZone: 'Africa/Johannesburg',
                year: 'numeric',
                month: '2-digit',
                day: '2-digit',
            });

            const getSouthAfricanDate = (value) => {
                const parts = southAfricanDateFormatter.formatToParts(
                    new Date(value)
                );

                const part = (type) =>
                    parts.find((item) => item.type === type)?.value;

                return `${part('year')}-${part('month')}-${part('day')}`;
            };

            if (!isValidDateOnly(from) || !isValidDateOnly(to)) {
                return res.status(400).json({
                    error: 'Provide valid from and to dates in YYYY-MM-DD format.',
                });
            }

            const startUTC = Date.parse(`${from}T00:00:00.000Z`);
            const endUTC = Date.parse(`${to}T00:00:00.000Z`);
            const inclusiveDays = Math.floor((endUTC - startUTC) / 86400000) + 1;

            if (inclusiveDays < 1) {
                return res.status(400).json({
                    error: 'The start date must be on or before the end date.',
                });
            }

            if (inclusiveDays > 366) {
                return res.status(400).json({
                    error: 'Analytics date ranges cannot exceed 366 days.',
                });
            }

            // South Africa uses UTC+02:00. Convert local midnight
            // boundaries to UTC so the selected dates are inclusive.
            const startDateTime = new Date(
                `${from}T00:00:00+02:00`
            ).toISOString();
            const endDateTime = new Date(
                `${addDateOnlyDays(to, 1)}T00:00:00+02:00`
            ).toISOString();

            // Fetch all orders in stable, bounded pages. This avoids
            // silently reporting only the first PostgREST response page.
            const ORDER_PAGE_SIZE = 500;
            const allOrders = [];
            let orderOffset = 0;

            while (true) {
                const { data, error } = await supabase
                    .from('orders')
                    .select(
                        'id, status, order_type, payment_method, subtotal, created_at'
                    )
                    .gte('created_at', startDateTime)
                    .lt('created_at', endDateTime)
                    .order('created_at', { ascending: true })
                    .order('id', { ascending: true })
                    .range(orderOffset, orderOffset + ORDER_PAGE_SIZE - 1);

                if (error) {
                    console.error(
                        'ADMIN ANALYTICS ORDER FETCH ERROR:',
                        error.code || error.message
                    );

                    return res.status(500).json({
                        error: 'Failed to calculate analytics orders.',
                    });
                }

                const pageRows = data || [];
                allOrders.push(...pageRows);

                if (pageRows.length < ORDER_PAGE_SIZE) {
                    break;
                }

                orderOffset += ORDER_PAGE_SIZE;
            }

            const statusCounts = {
                pending: 0,
                confirmed: 0,
                preparing: 0,
                ready: 0,
                completed: 0,
                cancelled: 0,
            };

            const orderTypes = {
                collection: { orders: 0, completedOrders: 0, revenue: 0 },
                delivery: { orders: 0, completedOrders: 0, revenue: 0 },
            };

            const paymentMethods = {
                cash: { orders: 0, revenue: 0 },
                eft: { orders: 0, revenue: 0 },
                card: { orders: 0, revenue: 0 },
            };

            const dailyMap = new Map();

            for (let dayIndex = 0; dayIndex < inclusiveDays; dayIndex += 1) {
                const date = addDateOnlyDays(from, dayIndex);
                dailyMap.set(date, {
                    date,
                    orders: 0,
                    completedOrders: 0,
                    cancelledOrders: 0,
                    revenue: 0,
                });
            }

            let completedRevenue = 0;
            let completedOrders = 0;
            let cancelledOrders = 0;
            let inProgressOrders = 0;
            const completedOrderIds = [];

            for (const order of allOrders) {
                const status = String(order.status || '').toLowerCase();
                const orderType = String(order.order_type || '').toLowerCase();
                const paymentMethod = String(order.payment_method || '').toLowerCase();
                const subtotalValue = Number(order.subtotal);
                const subtotal = Number.isFinite(subtotalValue) && subtotalValue > 0
                    ? subtotalValue
                    : 0;
                const dayKey = getSouthAfricanDate(order.created_at);
                const day = dailyMap.get(dayKey);

                if (Object.prototype.hasOwnProperty.call(statusCounts, status)) {
                    statusCounts[status] += 1;
                }

                if (day) {
                    day.orders += 1;
                }

                if (orderTypes[orderType]) {
                    orderTypes[orderType].orders += 1;
                }

                if (status === 'completed') {
                    completedOrders += 1;
                    completedRevenue += subtotal;
                    completedOrderIds.push(order.id);

                    if (day) {
                        day.completedOrders += 1;
                        day.revenue += subtotal;
                    }

                    if (orderTypes[orderType]) {
                        orderTypes[orderType].completedOrders += 1;
                        orderTypes[orderType].revenue += subtotal;
                    }

                    if (paymentMethods[paymentMethod]) {
                        paymentMethods[paymentMethod].orders += 1;
                        paymentMethods[paymentMethod].revenue += subtotal;
                    }
                } else if (status === 'cancelled') {
                    cancelledOrders += 1;

                    if (day) {
                        day.cancelledOrders += 1;
                    }
                } else if (
                    ['pending', 'confirmed', 'preparing', 'ready'].includes(status)
                ) {
                    inProgressOrders += 1;
                }
            }

            // Aggregate line items from completed orders only.
            // Fetch in small order-ID batches and page the line items
            // so popular-item results are not truncated by row limits.
            const itemTotals = new Map();
            const ORDER_ID_BATCH_SIZE = 100;
            const ITEM_PAGE_SIZE = 500;

            for (
                let idStart = 0;
                idStart < completedOrderIds.length;
                idStart += ORDER_ID_BATCH_SIZE
            ) {
                const orderIdBatch = completedOrderIds.slice(
                    idStart,
                    idStart + ORDER_ID_BATCH_SIZE
                );

                let itemOffset = 0;

                while (true) {
                    const { data, error } = await supabase
                        .from('order_items')
                        .select(`
                            order_id,
                            menu_item_id,
                            quantity,
                            price,
                            menu_items (
                                id,
                                name,
                                category
                            )
                        `)
                        .in('order_id', orderIdBatch)
                        .order('id', { ascending: true })
                        .range(itemOffset, itemOffset + ITEM_PAGE_SIZE - 1);

                    if (error) {
                        console.error(
                            'ADMIN ANALYTICS ITEM FETCH ERROR:',
                            error.code || error.message
                        );

                        return res.status(500).json({
                            error: 'Failed to calculate popular menu items.',
                        });
                    }

                    const itemRows = data || [];

                    for (const item of itemRows) {
                        const quantity = Number(item.quantity);
                        const price = Number(item.price);

                        if (
                            !Number.isFinite(quantity) ||
                            quantity <= 0 ||
                            !Number.isFinite(price) ||
                            price < 0
                        ) {
                            continue;
                        }

                        const linkedMenuItem = item.menu_items || null;
                        const menuItemId = item.menu_item_id ?? linkedMenuItem?.id ?? null;
                        const name = linkedMenuItem?.name || (
                            menuItemId !== null
                                ? `Menu item ${menuItemId}`
                                : 'Unavailable menu item'
                        );
                        const key = menuItemId !== null
                            ? String(menuItemId)
                            : `name:${name}`;

                        const current = itemTotals.get(key) || {
                            menuItemId,
                            name,
                            category: linkedMenuItem?.category || 'Other',
                            quantity: 0,
                            revenue: 0,
                        };

                        current.quantity += quantity;
                        current.revenue += quantity * price;
                        itemTotals.set(key, current);
                    }

                    if (itemRows.length < ITEM_PAGE_SIZE) {
                        break;
                    }

                    itemOffset += ITEM_PAGE_SIZE;
                }
            }

            const topItems = [...itemTotals.values()]
                .sort((a, b) => {
                    if (b.quantity !== a.quantity) {
                        return b.quantity - a.quantity;
                    }

                    return b.revenue - a.revenue;
                })
                .slice(0, 5)
                .map((item) => ({
                    ...item,
                    revenue: Number(item.revenue.toFixed(2)),
                }));

            const daily = [...dailyMap.values()].map((day) => ({
                ...day,
                revenue: Number(day.revenue.toFixed(2)),
            }));

            const roundedRevenue = Number(completedRevenue.toFixed(2));

            return res.status(200).json({
                period: {
                    from,
                    to,
                    timezone: 'Africa/Johannesburg',
                },
                summary: {
                    totalOrders: allOrders.length,
                    completedOrders,
                    cancelledOrders,
                    inProgressOrders,
                    completedRevenue: roundedRevenue,
                    averageCompletedOrderValue: completedOrders > 0
                        ? Number((completedRevenue / completedOrders).toFixed(2))
                        : 0,
                },
                statusCounts,
                orderTypes: {
                    collection: {
                        ...orderTypes.collection,
                        revenue: Number(orderTypes.collection.revenue.toFixed(2)),
                    },
                    delivery: {
                        ...orderTypes.delivery,
                        revenue: Number(orderTypes.delivery.revenue.toFixed(2)),
                    },
                },
                paymentMethods: {
                    cash: {
                        ...paymentMethods.cash,
                        revenue: Number(paymentMethods.cash.revenue.toFixed(2)),
                    },
                    eft: {
                        ...paymentMethods.eft,
                        revenue: Number(paymentMethods.eft.revenue.toFixed(2)),
                    },
                    card: {
                        ...paymentMethods.card,
                        revenue: Number(paymentMethods.card.revenue.toFixed(2)),
                    },
                },
                daily,
                topItems,
            });
        } catch (error) {
            console.error(
                'UNEXPECTED ADMIN ANALYTICS ERROR:',
                error.message
            );

            return res.status(500).json({
                error: 'Unable to calculate business analytics.',
            });
        }
    }
);


