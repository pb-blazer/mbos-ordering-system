function isPositiveInteger(value) {
    return Number.isSafeInteger(value) && value > 0;
}

function isValidSouthAfricanMobile(phone) {
    return /^0[6-9]\d{8}$/.test(phone);
}

/**
 * Returns YYMMDD in the Africa/Johannesburg time zone.
 *
 * Example:
 * 2026-10-29 in South Africa => 261029
 *
 * This does not rely on the server computer's local time zone.
 */
function getSouthAfricanDateStamp(date = new Date()) {
    const parts = new Intl.DateTimeFormat('en-GB', {
        timeZone: 'Africa/Johannesburg',
        year: '2-digit',
        month: '2-digit',
        day: '2-digit',
    }).formatToParts(date);

    const part = (type) =>
        parts.find((item) => item.type === type)?.value;

    return `${part('year')}${part('month')}${part('day')}`;
}

